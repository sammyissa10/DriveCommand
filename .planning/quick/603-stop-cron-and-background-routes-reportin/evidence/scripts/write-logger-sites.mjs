/** quick-603 — render objslot.json as the by-name markdown list in 03-logger-sites.md. */
import { readFileSync, writeFileSync } from 'node:fs';

const root = 'C:/Users/sammy/Projects/DriveCommand/.planning/quick/603-stop-cron-and-background-routes-reportin/evidence';
const d = JSON.parse(readFileSync(`${root}/objslot.json`, 'utf8'));

const byFile = new Map();
for (const s of d.objSlot) {
  const f = s.loc.replace(/:\d+$/, '');
  if (!byFile.has(f)) byFile.set(f, []);
  byFile.get(f).push(s);
}

const lines = [];
lines.push('# 03 — `logger.error` object-literal-in-slot-2 sites, by name');
lines.push('');
lines.push('**Generated by** `evidence/scripts/scan-logger-arity.mjs`, run from `apps/web`.');
lines.push('');
lines.push(`**${d.objSlot.length} sites across ${byFile.size} files**, out of ${d.total} total \`logger.error\` calls.`);
lines.push('');
lines.push('Each row is `file:line`, then the second argument as written. The bucket column is filled');
lines.push('in `05-logger-classification.md` (Task 5).');
lines.push('');
for (const [file, sites] of [...byFile.entries()].sort()) {
  lines.push(`### \`${file}\` — ${sites.length}`);
  lines.push('');
  lines.push('| line | slot-2 argument as written |');
  lines.push('|---|---|');
  for (const s of sites) {
    const line = s.loc.slice(file.length + 1);
    const arg = s.arg2.replace(/\|/g, '\\|');
    lines.push(`| ${line} | \`${arg.length > 150 ? arg.slice(0, 147) + '...' : arg}\` |`);
  }
  lines.push('');
}
writeFileSync(`${root}/03-logger-sites.md`, lines.join('\n'));
console.log('wrote 03-logger-sites.md —', d.objSlot.length, 'sites across', byFile.size, 'files');
